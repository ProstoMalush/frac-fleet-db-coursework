-- Проект одногруппницы: «Проектирование БД замеров по скважинам».
-- PostgreSQL 15. Все объекты и значения учебные, синтетические.
-- Схема partner_1 автономна: FK на frac_core здесь намеренно отсутствуют.

CREATE SCHEMA IF NOT EXISTS partner_1;
COMMENT ON SCHEMA partner_1 IS
'Учебная схема измерений по скважинам. Синтетические данные; локальные ID принадлежат только этой схеме.';

CREATE TABLE IF NOT EXISTS partner_1.source_field (
    source_field_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    field_code      VARCHAR(30) NOT NULL UNIQUE,
    field_name      VARCHAR(150) NOT NULL,
    region_name     VARCHAR(100) NOT NULL,
    description     TEXT,
    CONSTRAINT ck_p1_field_code_nonempty CHECK (btrim(field_code) <> ''),
    CONSTRAINT ck_p1_field_name_nonempty CHECK (btrim(field_name) <> '')
);

CREATE TABLE IF NOT EXISTS partner_1.source_well (
    source_well_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_field_id     BIGINT NOT NULL,
    well_code           VARCHAR(40) NOT NULL,
    well_type           VARCHAR(20) NOT NULL,
    well_status         VARCHAR(20) NOT NULL,
    commissioning_date  DATE,
    design_depth_m      NUMERIC(8,2),
    CONSTRAINT fk_p1_well_field FOREIGN KEY (source_field_id)
        REFERENCES partner_1.source_field(source_field_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT uq_p1_well_field_code UNIQUE (source_field_id, well_code),
    CONSTRAINT ck_p1_well_type CHECK (well_type IN ('production','injection','observation')),
    CONSTRAINT ck_p1_well_status CHECK (well_status IN ('active','suspended','abandoned','under_repair')),
    CONSTRAINT ck_p1_well_depth CHECK (design_depth_m IS NULL OR design_depth_m > 0)
);

CREATE TABLE IF NOT EXISTS partner_1.measurement_parameter (
    parameter_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parameter_code  VARCHAR(30) NOT NULL UNIQUE,
    parameter_name  VARCHAR(120) NOT NULL,
    unit_name       VARCHAR(30) NOT NULL,
    min_value       NUMERIC(14,4) NOT NULL,
    max_value       NUMERIC(14,4) NOT NULL,
    description     TEXT,
    is_active       BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_p1_parameter_range CHECK (max_value > min_value)
);

CREATE TABLE IF NOT EXISTS partner_1.measurement_method (
    method_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    method_code     VARCHAR(30) NOT NULL UNIQUE,
    method_name     VARCHAR(120) NOT NULL,
    description     TEXT
);

CREATE TABLE IF NOT EXISTS partner_1.measuring_device (
    device_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_code         VARCHAR(30) NOT NULL UNIQUE,
    device_type         VARCHAR(80) NOT NULL,
    serial_number       VARCHAR(60) NOT NULL UNIQUE,
    manufacturer        VARCHAR(100) NOT NULL,
    calibration_date    DATE NOT NULL,
    next_calibration_date DATE NOT NULL,
    device_status       VARCHAR(20) NOT NULL,
    CONSTRAINT ck_p1_device_calibration CHECK (next_calibration_date > calibration_date),
    CONSTRAINT ck_p1_device_status CHECK (device_status IN ('operating','verification','out_of_service'))
);

CREATE TABLE IF NOT EXISTS partner_1.measurement_operator (
    operator_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operator_code   VARCHAR(30) NOT NULL UNIQUE,
    operator_name   VARCHAR(120) NOT NULL,
    qualification   VARCHAR(100) NOT NULL,
    operator_status VARCHAR(20) NOT NULL DEFAULT 'active',
    CONSTRAINT ck_p1_operator_status CHECK (operator_status IN ('active','inactive'))
);

CREATE TABLE IF NOT EXISTS partner_1.measurement_session (
    session_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_code        VARCHAR(40) NOT NULL UNIQUE,
    source_well_id      BIGINT NOT NULL,
    method_id           BIGINT NOT NULL,
    device_id           BIGINT NOT NULL,
    operator_id         BIGINT NOT NULL,
    period_no           SMALLINT NOT NULL,
    measured_at         TIMESTAMPTZ NOT NULL,
    quality_status      VARCHAR(20) NOT NULL,
    notes               TEXT,
    CONSTRAINT fk_p1_session_well FOREIGN KEY (source_well_id)
        REFERENCES partner_1.source_well(source_well_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_p1_session_method FOREIGN KEY (method_id)
        REFERENCES partner_1.measurement_method(method_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_p1_session_device FOREIGN KEY (device_id)
        REFERENCES partner_1.measuring_device(device_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_p1_session_operator FOREIGN KEY (operator_id)
        REFERENCES partner_1.measurement_operator(operator_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT uq_p1_session_well_period UNIQUE (source_well_id, period_no),
    CONSTRAINT ck_p1_period_no CHECK (period_no BETWEEN 0 AND 42),
    CONSTRAINT ck_p1_session_quality CHECK (quality_status IN ('valid','suspect','rejected'))
);

CREATE TABLE IF NOT EXISTS partner_1.well_measurement (
    measurement_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id      BIGINT NOT NULL,
    parameter_id    BIGINT NOT NULL,
    measured_value  NUMERIC(14,4) NOT NULL,
    quality_flag    VARCHAR(20) NOT NULL DEFAULT 'valid',
    CONSTRAINT fk_p1_measurement_session FOREIGN KEY (session_id)
        REFERENCES partner_1.measurement_session(session_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_p1_measurement_parameter FOREIGN KEY (parameter_id)
        REFERENCES partner_1.measurement_parameter(parameter_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT uq_p1_measurement_session_parameter UNIQUE (session_id, parameter_id),
    CONSTRAINT ck_p1_measured_value_reasonable CHECK (measured_value BETWEEN -1000 AND 1000000),
    CONSTRAINT ck_p1_measurement_quality CHECK (quality_flag IN ('valid','suspect','rejected'))
);

CREATE INDEX IF NOT EXISTS idx_p1_source_well_code
    ON partner_1.source_well (well_code);
CREATE INDEX IF NOT EXISTS idx_p1_session_measured_at
    ON partner_1.measurement_session (measured_at);
CREATE INDEX IF NOT EXISTS idx_p1_session_well_time
    ON partner_1.measurement_session (source_well_id, measured_at DESC);
CREATE INDEX IF NOT EXISTS idx_p1_measurement_parameter
    ON partner_1.well_measurement (parameter_id, session_id);

COMMENT ON TABLE partner_1.source_field IS 'Копия справочной идентификации месторождений со стороны источника замеров; код используется для межсхемного сопоставления.';
COMMENT ON TABLE partner_1.source_well IS 'Регистр скважин источника замеров. source_well_id — локальный ID схемы partner_1, не равен по смыслу frac_core.well_id.';
COMMENT ON TABLE partner_1.measurement_parameter IS 'Справочник измеряемых параметров и единиц измерения.';
COMMENT ON TABLE partner_1.measurement_method IS 'Справочник методик/видов измерительных работ.';
COMMENT ON TABLE partner_1.measuring_device IS 'Приборы, использованные при проведении измерительных сессий.';
COMMENT ON TABLE partner_1.measurement_operator IS 'Условный справочник операторов, выполняющих замеры; все имена учебные.';
COMMENT ON TABLE partner_1.measurement_session IS 'Сессия замеров по одной скважине в конкретный момент времени.';
COMMENT ON TABLE partner_1.well_measurement IS 'Фактические значения параметров в рамках измерительной сессии; одна строка — один параметр одной сессии.';
COMMENT ON COLUMN partner_1.source_well.source_well_id IS 'Локальный первичный ключ partner_1. Для интеграции с frac_core нельзя сопоставлять строки только по числовому ID.';
COMMENT ON COLUMN partner_1.well_measurement.measured_value IS 'Числовое значение параметра в единицах, указанных в measurement_parameter.unit_name.';
